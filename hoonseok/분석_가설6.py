# 가설 6 (원래 문장): 아동인구 규모가 비슷한 지역이라도 소아청소년과 전문의 수에 수도권/비수도권 차이가 남을 것이다.
# 방법: 1만 명당으로 나누지 않고, 아동인구가 비슷한 시도끼리 짝을 지어 전문의 수(명)를 그대로 비교
# 실행 위치: C:\Users\Administrator\mini2  (mini2 바로 위 폴더)
import pandas as pd
import matplotlib.pyplot as plt

plt.rc('font', family='Malgun Gothic')
plt.rcParams['axes.unicode_minus'] = False

# '비슷한 규모' 기준: 수도권 시도 아동인구의 ±20% 안 (결과를 보기 전에 정함)
아래기준 = 0.8
위기준 = 1.2

# [1단계] 데이터 불러오기 (분석_가설6.py와 같음)
인구 = pd.read_csv('./mini2/data/인구_시단위_2025.csv', encoding='utf-8-sig')
전문의 = pd.read_csv('./mini2/data/지역별종별_전문과목별전문의수_2025년4분기.csv', encoding='utf-8-sig')

# [2단계] 필요한 칸 이름 바꾸기
# 첫 번째 칸 = 시도, 두 번째 칸 = 요양기관종별, 14번째 칸 = 소아청소년과
제목 = '지역별종별_전문과목별전문의수(단위_명)_2025년4분기'
전문의 = 전문의.rename(columns={제목: '시도', 'Unnamed: 1': '요양기관종별', 'Unnamed: 13': '소아청소년과'})
전문의 = 전문의.dropna(axis=0)

# 원래 칸 이름 줄을 보여주고(소아청소년과가 맞는지 확인) 지우기
print('[파일 확인] 원래 칸 이름 줄:')
print(전문의[전문의['시도'] == '시도'][['시도', '요양기관종별', '소아청소년과']])
전문의 = 전문의[전문의['시도'] != '시도']

# [3단계] 숫자 정리: '1,523' → 1523, '-' → 0
원래값목록 = list(전문의['소아청소년과'])
숫자목록 = []
for 값 in 원래값목록:
    글자 = str(값)
    글자 = 글자.replace(',', '')
    if 글자 == '-':
        숫자목록.append(0)
    else:
        숫자목록.append(int(글자))

정리표 = pd.DataFrame({
    '시도약칭': list(전문의['시도']),
    '요양기관종별': list(전문의['요양기관종별']),
    '소아과전문의': 숫자목록
})

# [4단계] '계' 줄만 쓰기 (계 = 모든 요양기관종별을 더한 값)
계표 = 정리표[정리표['요양기관종별'] == '계']
종별표 = 정리표[정리표['요양기관종별'] != '계']

# 확인: 계 값 = 나머지 종별을 더한 값인지
종별합 = 종별표.groupby('시도약칭')['소아과전문의'].sum()
종별합 = 종별합.reset_index()
종별합 = 종별합.rename(columns={'소아과전문의': '종별합'})
계확인 = pd.merge(계표, 종별합, on='시도약칭', how='inner')
계확인['차이'] = 계확인['소아과전문의'] - 계확인['종별합']
print('[확인] 계와 종별합이 다른 시도 수:', len(계확인[계확인['차이'] != 0]), '(0이어야 함)')

# [5단계] 시도 이름 맞추기 (서울 → 서울특별시)
시도이름 = {'서울': '서울특별시', '부산': '부산광역시', '대구': '대구광역시', '인천': '인천광역시',
         '광주': '광주광역시', '대전': '대전광역시', '울산': '울산광역시', '세종': '세종특별자치시',
         '경기': '경기도', '강원': '강원특별자치도', '충북': '충청북도', '충남': '충청남도',
         '전북': '전북특별자치도', '전남': '전라남도', '경북': '경상북도', '경남': '경상남도',
         '제주': '제주특별자치도'}
약칭목록 = list(계표['시도약칭'])
정식이름목록 = []
for 약칭 in 약칭목록:
    if 약칭 in 시도이름:
        정식이름목록.append(시도이름[약칭])
    else:
        정식이름목록.append('이름없음_' + 약칭)

전문의표 = pd.DataFrame({
    '시도': 정식이름목록,
    '시도약칭': 약칭목록,
    '소아과전문의': list(계표['소아과전문의'])
})

# [6단계] 아동인구를 시도별로 합치기 (시군구 229개 → 시도 17개)
시도인구 = 인구.groupby(['시도', '권역'])['아동인구'].sum()
시도인구 = 시도인구.reset_index()

# 권역을 두 묶음으로: 수도권 / 비수도권
시도인구['권역2'] = '비수도권'
시도인구.loc[시도인구['권역'] == '수도권', '권역2'] = '수도권'

# [7단계] 두 표 합치기 + 검증
d = pd.merge(시도인구, 전문의표, on='시도', how='outer')
print('[검증] 결합 후 시도 수:', len(d), '(17이어야 함)')
print('[검증] 칸별 빈 값 개수 (모두 0이어야 함):')
print(d.isnull().sum())
print('[검증] 아동인구 합계:', d['아동인구'].sum(), '명 (7139629명이어야 함)')

# [8단계] 17개 시도를 아동인구 순서로 정렬해서 보여주기
d = d.sort_values(by='아동인구', ascending=False)
print('\n[결과 1] 아동인구 순서로 본 시도별 소아청소년과 전문의 수')
print(d[['시도약칭', '권역2', '아동인구', '소아과전문의']])

# [9단계] 수도권 시도마다 아동인구가 ±20% 안인 비수도권 시도를 짝으로 고르기
수도권표 = d[d['권역2'] == '수도권']
비수도권표 = d[d['권역2'] == '비수도권']

수도권이름 = list(수도권표['시도약칭'])
수도권아동 = list(수도권표['아동인구'])
수도권전문의 = list(수도권표['소아과전문의'])
비수도권이름 = list(비수도권표['시도약칭'])
비수도권아동 = list(비수도권표['아동인구'])
비수도권전문의 = list(비수도권표['소아과전문의'])

# 찾은 짝을 담을 빈 리스트
짝_수도권 = []
짝_수도권아동 = []
짝_수도권전문의 = []
짝_비수도권 = []
짝_비수도권아동 = []
짝_비수도권전문의 = []
짝_아동비율 = []
비교가능수도권수 = 0

print('\n[결과 2] 짝 찾기 (기준: 수도권 시도 아동인구의 80%~120%)')
for i in range(len(수도권이름)):
    찾은수 = 0
    for j in range(len(비수도권이름)):
        비율 = 비수도권아동[j] / 수도권아동[i]
        if 비율 >= 아래기준:
            if 비율 <= 위기준:
                짝_수도권.append(수도권이름[i])
                짝_수도권아동.append(수도권아동[i])
                짝_수도권전문의.append(수도권전문의[i])
                짝_비수도권.append(비수도권이름[j])
                짝_비수도권아동.append(비수도권아동[j])
                짝_비수도권전문의.append(비수도권전문의[j])
                짝_아동비율.append(비율)
                찾은수 += 1
    if 찾은수 == 0:
        print(수도권이름[i], ': 비슷한 규모의 비수도권 시도 없음 → 비교에서 뺌')
    else:
        print(수도권이름[i], ': 짝', 찾은수, '개')
        비교가능수도권수 += 1

# [10단계] 짝마다 전문의 수 나란히 비교
수도권이많음 = []
for k in range(len(짝_수도권)):
    if 짝_수도권전문의[k] > 짝_비수도권전문의[k]:
        수도권이많음.append('예')
    else:
        수도권이많음.append('아니오')

짝표 = pd.DataFrame({
    '수도권': 짝_수도권,
    '수도권아동': 짝_수도권아동,
    '수도권전문의': 짝_수도권전문의,
    '비수도권': 짝_비수도권,
    '비수도권아동': 짝_비수도권아동,
    '비수도권전문의': 짝_비수도권전문의,
    '아동비율(비/수)': 짝_아동비율,
    '수도권이_더_많음': 수도권이많음
})
짝표['아동비율(비/수)'] = 짝표['아동비율(비/수)'].round(2)
짝표['전문의차이(수-비)'] = 짝표['수도권전문의'] - 짝표['비수도권전문의']
print('\n[결과 3] 짝별 소아청소년과 전문의 수 비교')
print(짝표)

# [11단계] 판정 (규칙은 결과를 보기 전에 정함)
짝수 = len(짝표)
수도권우세수 = len(짝표[짝표['수도권이_더_많음'] == '예'])
if 짝수 == 0:
    판정 = '검증 불가'
else:
    if 수도권우세수 == 짝수:
        판정 = '지지'
    else:
        if 수도권우세수 == 0:
            판정 = '지지되지 않음'
        else:
            판정 = '부분 지지'

print('\n[판정]', 판정)
print('비교한 짝:', 짝수, '개 / 수도권 쪽이 더 많은 짝:', 수도권우세수, '개')
print('비교 가능한 수도권 시도:', 비교가능수도권수, '개 (전체 수도권 시도 3개 중)')
if 비교가능수도권수 <= 2:
    print('한계: 비교 가능한 수도권 시도가 적어서, 수도권 전체에 대한 결론으로 보기 어려움')

# [12단계] 그래프: 짝마다 수도권(파랑) → 비수도권(주황) 순서로 막대
# 아동인구를 '만 명' 단위로 바꾸기 (438984 → 43.9)
짝표['수도권아동_만'] = (짝표['수도권아동'] / 10000).round(1)
짝표['비수도권아동_만'] = (짝표['비수도권아동'] / 10000).round(1)
수도권아동만 = list(짝표['수도권아동_만'])
비수도권아동만 = list(짝표['비수도권아동_만'])

plt.figure(figsize=(10, 6))
for k in range(len(짝_수도권)):
    # 막대 위 글자: 전문의 수 + 아동인구(만 명)
    수도권글자 = f'{짝_수도권전문의[k]}명\n(아동 {수도권아동만[k]}만)'
    비수도권글자 = f'{짝_비수도권전문의[k]}명\n(아동 {비수도권아동만[k]}만)'
    # 범례는 첫 번째 짝에만 붙이기
    if k == 0:
        수도권범례 = '수도권'
        비수도권범례 = '비수도권'
    else:
        수도권범례 = None
        비수도권범례 = None
    # x축 이름: 같은 수도권 시도가 두 번 나와도 겹치지 않게 짝 번호를 붙임
    막대1 = plt.bar(f'{k + 1}. {짝_수도권[k]}', 짝_수도권전문의[k], color='#2a78d6', width=0.6, label=수도권범례)
    막대2 = plt.bar(f'{k + 1}. {짝_비수도권[k]}', 짝_비수도권전문의[k], color='#eb6834', width=0.6, label=비수도권범례)
    plt.bar_label(막대1, labels=[수도권글자], padding=3, fontsize=9)  # 수업에 없음: bar_label은 수업에 있지만 labels=(막대 위 글자 직접 정하기)는 없음
    plt.bar_label(막대2, labels=[비수도권글자], padding=3, fontsize=9)  # 수업에 없음: 위와 같음

plt.title('아동인구 규모가 비슷한(±20%) 수도권·비수도권 시도의 소아청소년과 전문의 수\n(전문의 2025년 4분기, 인구 2025년)')
plt.xlabel('짝 번호. 시도 (같은 번호끼리 비교)')
plt.ylabel('소아청소년과 전문의 수 (명)')
plt.grid(True, alpha=0.3)
plt.legend()
plt.savefig('./mini2/images/훈석4_규모비슷한시도_소아과전문의.png')  # 수업에 없음: 그래프를 그림 파일로 저장하는 기능이 수업 자료에 없어서 사용
print('\n그래프 저장: ./mini2/images/훈석4_규모비슷한시도_소아과전문의.png')
plt.show()
