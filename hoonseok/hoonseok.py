import pandas as pd


df = pd.read_csv('./mini2/data/2025년 인구수.csv', encoding='euckr')

# print(df.head(5))      
# print(df.columns)       
# print(len(df))

# 칸이름 변경
df = df.rename(columns={'행정구역(시군구)별': '지역', '연령별': '연령', '2025년': '인구'})
df = df[['지역', '연령', '인구']]

# print(df.head(5))
# print(df.columns)

# 각 줄에 시/도 이름 추가
시도목록 = ['서울특별시', '부산광역시', '대구광역시', '인천광역시', '광주광역시',
          '대전광역시', '울산광역시', '세종특별자치시', '경기도', '강원특별자치도',
          '충청북도', '충청남도', '전북특별자치도', '전라남도', '경상북도',
          '경상남도', '제주특별자치도']

시도 = []          
현재시도 = ''      

for i in df['지역']:
    if i in 시도목록:      
        현재시도 = i       
    시도.append(현재시도)   

df['시도'] = 시도

# print(df[df['연령'] == '계'].head(30))

# [4단계] 완전히 똑같은 줄 빼기 (세종 중복)
print('중복 제거 전:', len(df))
df = df.drop_duplicates()
print('중복 제거 후:', len(df))

# [5단계] 합계 줄 빼기 (전국 줄, 시도 줄)
# ① 전국 줄 빼기
df = df[df['지역'] != '전국']
print('전국 제거 후:', len(df))

# ② 시도 줄 빼기 (세종은 아래에 시군구가 없으니 남긴다)
남길줄 = []
for i in df['지역']:
    if i in 시도목록 and i != '세종특별자치시':   # 시도 이름인데 세종이 아니면
        남길줄.append(False)                      # 뺀다
    else:
        남길줄.append(True)                       # 나머지는 남긴다
df = df[남길줄]
print('시도 제거 후:', len(df))

# [6단계] 출장소 줄 빼기 + 창원시(통합) 이름 정리
# 출장소는 구청·시청의 지점이라 위쪽 지역 인구에 이미 들어 있다
남길줄 = []
for i in df['지역']:
    if i[len(i)-3:] == '출장소':     # 이름 끝 세 글자가 '출장소'면
        남길줄.append(False)          # 뺀다
    else:
        남길줄.append(True)
df = df[남길줄]
print('출장소 제거 후:', len(df))

새이름 = []
for i in df['지역']:
    새이름.append(i.replace('(통합)', ''))   # '창원시(통합)' → '창원시'
df['지역'] = 새이름

# [7단계] 일반구 줄 빼기 (도 안의 시 아래에 있는 구 = 3층)
# 서울·광역시의 구(자치구, 2층)는 남기고, 도 소속인데 '구'로 끝나는 것만 뺀다
시도들 = list(df['시도'])
지역들 = list(df['지역'])
남길줄 = []
for n in range(len(df)):                  # 0번 줄부터 마지막 줄까지 번호로 반복
    시도이름 = 시도들[n]
    지역이름 = 지역들[n]
    if 시도이름[len(시도이름)-1] == '도' and 지역이름[len(지역이름)-1] == '구':
        남길줄.append(False)          # 도 소속 + 구로 끝남 → 일반구 → 뺀다
    else:
        남길줄.append(True)
df = df[남길줄]
print('일반구 제거 후:', len(df))
print('남은 지역 수:', len(df) / 102)
print('남은 총인구 합:', df[df['연령'] == '계']['인구'].sum(), '(전국 51117378과 같아야 함)')

# [8단계] 지역별로 총인구·아동인구·고령인구 계산
아동연령 = []
for n in range(0, 19):
    아동연령.append(str(n) + '세')     # '0세' ~ '18세'

고령연령 = []
for n in range(65, 100):
    고령연령.append(str(n) + '세')     # '65세' ~ '99세'
고령연령.append('100세 이상')

아동줄 = []
고령줄 = []
for i in df['연령']:
    아동줄.append(i in 아동연령)        # 0~18세 줄이면 True
    고령줄.append(i in 고령연령)        # 65세 이상 줄이면 True

총인구 = df[df['연령'] == '계'].groupby(['시도', '지역'])['인구'].sum()
아동인구 = df[아동줄].groupby(['시도', '지역'])['인구'].sum()
고령인구 = df[고령줄].groupby(['시도', '지역'])['인구'].sum()

결과 = pd.DataFrame({'총인구': 총인구, '아동인구': 아동인구, '고령인구': 고령인구})
결과['고령화율'] = (결과['고령인구'] / 결과['총인구'] * 100).round(2)
결과 = 결과.reset_index()                          # 시도, 지역을 다시 일반 칸으로
결과 = 결과.rename(columns={'지역': '시군구'})

# [9단계] 구분 칸 추가 (시도_시군구, 유형, 권역) + 저장
결과['시도_시군구'] = 결과['시도'] + ' ' + 결과['시군구']   # 예: '서울특별시 중구'

유형 = []
for i in 결과['시군구']:
    유형.append(i[len(i)-1])           # 마지막 글자: 구 / 시 / 군
결과['유형'] = 유형

수도권 = ['서울특별시', '경기도', '인천광역시']
광역시 = ['부산광역시', '대구광역시', '광주광역시', '대전광역시', '울산광역시']
권역 = []
for i in 결과['시도']:
    if i in 수도권:
        권역.append('수도권')
    elif i in 광역시:
        권역.append('비수도권 광역시')
    else:
        권역.append('비수도권 그외')
결과['권역'] = 권역

결과 = 결과[['시도_시군구', '총인구', '아동인구', '고령인구', '고령화율',
           '시도', '시군구', '유형', '권역']]

print(결과.head())
print(결과['유형'].value_counts())
print(결과['권역'].value_counts())

결과.to_csv('./mini2/data/인구_시단위_2025.csv', index=False, encoding='utf-8-sig')
print('저장 완료')
