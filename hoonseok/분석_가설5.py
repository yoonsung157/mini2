import pandas as pd
import matplotlib.pyplot as plt
import os

plt.rc('font', family='Malgun Gothic')        # 한글 글꼴 (수업 day09와 같은 방식)
plt.rcParams['axes.unicode_minus'] = False

BLUE, ORANGE = '#2a78d6', '#eb6834'          
INK, MUTED = '#0b0b0b', '#52514e'

# ===== [1단계] 데이터 불러오기 =====
인구 = pd.read_csv('./mini2/data/인구_시단위_2025.csv', encoding='utf-8-sig')    
병원 = pd.read_csv('./mini2/data/병원정보.csv', encoding='cp949')           

# 종합병원 + 상급종합병원만 
병원 = 병원[병원['종별코드명'].isin(['상급종합', '종합병원'])]
print('종합·상급종합병원 수:', len(병원))

# ===== [2단계] 병원 데이터의 지역 이름을 내 데이터 이름으로 바꾸기 =====
# 병원 데이터는 '서울|강남구', '부산|부산중구', '경기|수원장안구' 처럼 적혀 있음
# 내 데이터는 '서울특별시 강남구', '부산광역시 중구', '경기도 수원시' 처럼 적혀 있음
시도이름 = {'서울': '서울특별시', '부산': '부산광역시', '대구': '대구광역시', '인천': '인천광역시',
         '광주': '광주광역시', '대전': '대전광역시', '울산': '울산광역시', '세종시': '세종특별자치시',
         '경기': '경기도', '강원': '강원특별자치도', '충북': '충청북도', '충남': '충청남도',
         '전북': '전북특별자치도', '전남': '전라남도', '경북': '경상북도', '경남': '경상남도',
         '제주': '제주특별자치도'}
광역시앞글자 = ['부산', '대구', '인천', '광주', '대전', '울산']

# 인천은 2026년에 구가 새로 나뉨(제물포구·영종구·서해구·검단구). 2025년 인구에는 옛 중구·동구·서구로 있음
# 양쪽 모두 하나로 묶어서 비교
인천새구 = ['제물포구', '영종구', '서해구', '검단구']
인천묶음 = '인천광역시 중구·동구·서구'

열쇠목록 = []
for 시도, 시군구 in zip(병원['시도코드명'], 병원['시군구코드명']):
    # 시도 이름 정리 ('전남광주'는 광주 구면 광주광역시, 나머지는 전라남도)
    if 시도 == '전남광주':
        if 시군구[:2] == '광주' and 시군구[-1] == '구':
            시도 = '광주'
        else:
            시도 = '전남'
    시도전체 = 시도이름[시도]

    # 시군구 이름 정리
    if 시도전체 == '세종특별자치시':
        이름 = '세종특별자치시'
    elif 시도 in 광역시앞글자 and 시군구 != '부산진구':
        이름 = 시군구[2:]                       # '부산중구' → '중구'
    elif 시도전체[-1] == '도' and 시군구[-1] == '구':
        이름 = 시군구[:2] + '시'                # '수원장안구' → '수원시' (일반구는 시로 합침)
    else:
        이름 = 시군구

    열쇠 = 시도전체 + ' ' + 이름
    if 시도전체 == '인천광역시' and 이름 in 인천새구:
        열쇠 = 인천묶음
    열쇠목록.append(열쇠)
병원['시도_시군구'] = 열쇠목록

# 내 인구 데이터의 인천 중구·동구·서구도 하나로 묶기
인천옛구 = ['인천광역시 중구', '인천광역시 동구', '인천광역시 서구']
묶을줄 = 인구[인구['시도_시군구'].isin(인천옛구)]
새줄 = pd.DataFrame([{
    '시도_시군구': 인천묶음, '총인구': 묶을줄['총인구'].sum(), '아동인구': 묶을줄['아동인구'].sum(),
    '고령인구': 묶을줄['고령인구'].sum(), '고령화율': 0, '시도': '인천광역시',
    '시군구': '중구·동구·서구', '유형': '구', '권역': '수도권'}])
새줄['고령화율'] = (새줄['고령인구'] / 새줄['총인구'] * 100).round(2)
인구 = pd.concat([인구[~인구['시도_시군구'].isin(인천옛구)], 새줄], ignore_index=True)
print('비교 단위 수:', len(인구), '(229개 중 인천 3개를 1개로 묶음)')

# 짝이 안 맞는 병원이 있는지 확인 (0이어야 함)
못찾음 = 병원[~병원['시도_시군구'].isin(인구['시도_시군구'])]
print('짝이 안 맞는 병원 수:', len(못찾음), 못찾음['시도_시군구'].unique())

# ===== [3단계] 지역별 병원 수 세고, 인구와 합치기 =====
병원수 = 병원.groupby('시도_시군구').size().rename('종합병원수').reset_index()
d = pd.merge(인구, 병원수, on='시도_시군구', how='left')
d['종합병원수'] = d['종합병원수'].fillna(0)                     # 병원이 없는 지역은 0곳
d['10만명당'] = d['종합병원수'] / d['총인구'] * 100000
d['종합병원없음'] = d['종합병원수'] == 0
print('종합병원이 하나도 없는 지역:', d['종합병원없음'].sum(), '/', len(d))
print('합친 병원 수 확인:', int(d['종합병원수'].sum()), '(384와 같아야 함)')

# ===== [4단계] 가설 5: 고령화율이 높을수록 10만 명당 종합병원 수가 적은가 =====
# 고령화율로 지역을 4묶음(낮은 순 25%씩)으로 나눈다
d['고령화구간'] = pd.qcut(d['고령화율'], 4, labels=['1구간(낮음)', '2구간', '3구간', '4구간(높음)'])

구간표 = d.groupby('고령화구간', observed=True).agg(
    지역수=('시도_시군구', 'count'), 고령화율최소=('고령화율', 'min'), 고령화율최대=('고령화율', 'max'),
    병원수=('종합병원수', 'sum'), 인구=('총인구', 'sum'), 없는비율=('종합병원없음', 'mean'))
구간표['10만명당'] = 구간표['병원수'] / 구간표['인구'] * 100000
구간표['없는비율'] = 구간표['없는비율'] * 100
print(구간표.round(2))

print('상관계수(고령화율 vs 10만 명당 병원 수):', round(d['고령화율'].corr(d['10만명당']), 3))
print('순위 상관계수(spearman):', round(d['고령화율'].corr(d['10만명당'], method='spearman'), 3))

# ===== [5단계] 가설 5': 같은 유형 안에서도 고령화율이 높은 쪽이 '종합병원 없음' 비율이 높은가 =====
# 유형(구/시/군)마다 고령화율 중앙값으로 반씩 나눈다
높음여부 = []
for 유형, 율 in zip(d['유형'], d['고령화율']):
    중앙값 = d[d['유형'] == 유형]['고령화율'].median()
    높음여부.append('고령화율 높은 절반' if 율 > 중앙값 else '고령화율 낮은 절반')
d['유형내구분'] = 높음여부

유형표 = d.groupby(['유형', '유형내구분']).agg(
    지역수=('시도_시군구', 'count'), 없는지역=('종합병원없음', 'sum'), 없는비율=('종합병원없음', 'mean'))
유형표['없는비율'] = 유형표['없는비율'] * 100
print(유형표.round(1))

# ===== [6단계] 시각화 =====
os.makedirs('./mini2/images', exist_ok=True)

def 꾸미기(ax, 제목):
    ax.set_title(제목, fontsize=13, color=INK, loc='left')
    ax.tick_params(colors=MUTED)
    for 테두리 in ['top', 'right', 'left']:
        ax.spines[테두리].set_visible(False)
    ax.grid(axis='y', color='#e6e6e3')
    ax.set_axisbelow(True)

# 그림 1. 고령화율 구간별 인구 10만 명당 종합·상급종합병원 수
fig, ax = plt.subplots(figsize=(8, 4.5))
이름표 = []
for 구간, 줄 in 구간표.iterrows():
    이름표.append(f'{구간}\n고령화율 {줄["고령화율최소"]:.0f}~{줄["고령화율최대"]:.0f}%')
bars = ax.bar(이름표, 구간표['10만명당'], color=BLUE, width=0.55)
글 = []
for 병원개수, 지역개수, 값 in zip(구간표['병원수'], 구간표['지역수'], 구간표['10만명당']):
    글.append(f'{값:.2f}곳\n(병원 {int(병원개수)}곳 / {지역개수}개 지역)')
ax.bar_label(bars, labels=글, padding=3, fontsize=10, color=INK)
ax.set_ylim(0, 구간표['10만명당'].max() * 1.3)
꾸미기(ax, '고령화율 구간별 인구 10만 명당 종합·상급종합병원 수')
fig.tight_layout()
fig.savefig('./mini2/images/훈석1_고령화율구간_병원수.png', dpi=200)

# 그림 2. 유형별·고령화율별 '종합병원이 하나도 없는 지역' 비율
fig, ax = plt.subplots(figsize=(8, 4.5))
유형순서 = ['구', '시', '군']
위치 = range(len(유형순서))
너비 = 0.36
for k, (구분, 색) in enumerate([('고령화율 낮은 절반', BLUE), ('고령화율 높은 절반', ORANGE)]):
    값들 = []
    글들 = []
    for 유형 in 유형순서:
        줄 = 유형표.loc[(유형, 구분)]
        값들.append(줄['없는비율'])
        글들.append(f'{줄["없는비율"]:.0f}%\n({int(줄["없는지역"])}/{int(줄["지역수"])})')
    x = [p + (k - 0.5) * (너비 + 0.02) for p in 위치]
    bars = ax.bar(x, 값들, width=너비, color=색, label=구분)
    ax.bar_label(bars, labels=글들, padding=3, fontsize=10, color=INK)
ax.set_xticks(list(위치), ['자치구', '시', '군'])
ax.set_ylim(0, 115)
ax.set_ylabel('종합병원이 없는 지역 비율(%)', color=MUTED)
ax.legend(frameon=False, loc='upper left')
꾸미기(ax, '같은 유형 안에서 고령화율에 따른 \'종합병원 없는 지역\' 비율')
fig.tight_layout()
fig.savefig('./mini2/images/훈석2_유형별_종합병원없는비율.png', dpi=200)

plt.show()
