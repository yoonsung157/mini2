import pandas as pd

# 1. 지역별 건강 보험 적용 인구
보험적용인구_df = pd.read_csv("data/data_hsyonii/시도별_보험적용인구.csv")

# ================ 데이터 정제 ====================
# 지역 이름과 의료보장적용인구만 추출
보험적용인구_df = 보험적용인구_df.iloc[:, 0:2]
보험적용인구_df.columns = ["지역", "인구수"] # 칼럼명 수정

# 빈 행과 주석 제거
# df.isna() : 데이터 자리마다 결측치 여부를 True/False로 채워 데이터프레임 반환
print(보험적용인구_df[ 보험적용인구_df.isna().sum(axis=1) > 0 ].to_string()) # 행 별로 결측치가 하나라도있으면 해당행 전체반환(삭제 전 확인용)
# df.dropna() : 결측치 있는 행 전체 제거 
# ignore_index=True : 인덱스 재정렬
보험적용인구_df = 보험적용인구_df.dropna(ignore_index=True)
# print(보험적용인구_df)

# 데이터 공백제거, 숫자형 데이터 정수변환
보험적용인구_df['지역'] = 보험적용인구_df['지역'].str.strip()
보험적용인구_df['인구수'] = 보험적용인구_df["인구수"].astype(int)

